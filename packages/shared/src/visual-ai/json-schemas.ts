/** JSON Schema subset for Gemini `responseJsonSchema` (visual analysis). */
export const visualAnalysisBatchJsonSchema = {
  type: 'object',
  properties: {
    characters: {
      type: 'array',
      items: {
        type: 'object',
        properties: {
          name: { type: 'string' },
          description: { type: 'string' },
          approximateAge: { type: 'string' },
          genderPresentation: { type: 'string' },
          skinTone: { type: 'string' },
          facialFeatures: { type: 'string' },
          hairstyle: { type: 'string' },
          hairColor: { type: 'string' },
          bodyBuild: { type: 'string' },
          clothing: { type: 'string' },
          accessories: { type: 'string' },
          distinguishingCharacteristics: { type: 'string' },
          visualConsistencyInstructions: { type: 'string' },
          canonicalVisualDescription: { type: 'string' },
        },
        required: [
          'name',
          'description',
          'approximateAge',
          'facialFeatures',
          'hairstyle',
          'hairColor',
          'clothing',
          'distinguishingCharacteristics',
          'visualConsistencyInstructions',
          'canonicalVisualDescription',
        ],
      },
    },
    scenes: {
      type: 'array',
      items: {
        type: 'object',
        properties: {
          sceneNumber: { type: 'number' },
          mainSubject: { type: 'string' },
          charactersPresent: { type: 'array', items: { type: 'string' } },
          characterAppearances: {
            type: 'array',
            items: {
              type: 'object',
              properties: {
                name: { type: 'string' },
                appearance: { type: 'string' },
                clothing: { type: 'string' },
                ageRange: { type: 'string' },
                facialExpression: { type: 'string' },
                bodyPosture: { type: 'string' },
                physicalAction: { type: 'string' },
              },
              required: [
                'name',
                'appearance',
                'clothing',
                'facialExpression',
                'bodyPosture',
                'physicalAction',
              ],
            },
          },
          location: { type: 'string' },
          environment: { type: 'string', description: 'Flat string, not object' },
          timeOfDay: { type: 'string' },
          weather: { type: 'string' },
          lighting: { type: 'string', description: 'Flat string, not object' },
          cameraAngle: { type: 'string' },
          cameraDistance: { type: 'string' },
          composition: { type: 'string' },
          backgroundDetails: { type: 'string' },
          emotionalAtmosphere: { type: 'string' },
          visualStyleNotes: { type: 'string' },
          aspectRatio: { type: 'string' },
          imagePrompt: { type: 'string' },
          negativePrompt: { type: 'string' },
        },
        required: [
          'sceneNumber',
          'mainSubject',
          'location',
          'environment',
          'timeOfDay',
          'weather',
          'lighting',
          'cameraAngle',
          'cameraDistance',
          'composition',
          'backgroundDetails',
          'emotionalAtmosphere',
          'visualStyleNotes',
          'imagePrompt',
          'negativePrompt',
        ],
      },
    },
  },
  required: ['scenes'],
} as const;
